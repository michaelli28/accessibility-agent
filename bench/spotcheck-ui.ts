// Local review UI for bench/SPOTCHECK.md: one screen per drawn item, the page under test beside the
// recorded label, and the verdict saved as you go. Nothing here judges anything -- it only shows what
// spotcheck.ts drew and records what the human says back.
//
//   npx tsx bench/spotcheck-ui.ts [--port 4174]     then open http://127.0.0.1:4174
//
// It serves the corpus itself (same MOUNTS as bench/serve.ts), so bench/serve.ts does NOT need to be
// running and the preview is same-origin, which is what lets it outline the target element.
// Verdicts land in bench/spotcheck-answers.json as you type; SPOTCHECK.md is only ever touched by the
// explicit "write into SPOTCHECK.md" action, because spotcheck.ts rewrites that file wholesale.
import { createHash } from "node:crypto";
import { createServer } from "node:http";
import {
  existsSync,
  readFileSync,
  realpathSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, extname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { MOUNTS, SERVE_ORIGIN } from "./serve.js";

const BENCH = dirname(fileURLToPath(import.meta.url));
const SPOTCHECK_MD = join(BENCH, "SPOTCHECK.md");
const ANSWERS_JSON = join(BENCH, "spotcheck-answers.json");
const DEFAULT_PORT = 4174;

const VERDICTS = ["agree", "disagree", "unsure"] as const;
const VerdictSchema = z.enum(VERDICTS);
export type Verdict = z.infer<typeof VerdictSchema>;

const AnswerSchema = z
  .object({ verdict: VerdictSchema.nullable(), note: z.string() })
  .strict();
const GenerationSchema = z
  .object({
    itemsSha256: z.string(),
    answers: z.record(z.string(), AnswerSchema),
  })
  .strict();

const AnswersFileSchema = z
  .object({
    // Which DRAWN ITEMS the CURRENT answers belong to: a redraw changes the items under the same
    // numbers, so answers carried across one would silently describe different elements. Keyed on
    // the items' own fields, NOT the file bytes -- writing verdicts back into the file changes its
    // bytes, and hashing those made the write invalidate the answers it had just saved.
    itemsSha256: z.string(),
    answers: z.record(z.string(), AnswerSchema),
    // Every earlier draw's verdicts, kept forever. Regenerating a worklist is an ordinary operation
    // (a different --sample, a re-run at a new sha), and it used to prune this file to nothing on
    // the next keystroke. The worklist is disposable; this file is the record. It only ever grows.
    superseded: z.array(GenerationSchema).default([]),
    // What write-md last copied into the worklist, so its guard can tell that copy from a hand
    // edit. Not a verdict: a redraw starts a generation without it.
    writtenToMd: z.record(z.string(), AnswerSchema).optional(),
  })
  .strict();
export type AnswersFile = z.infer<typeof AnswersFileSchema>;

// Move the current generation into the archive and start a clean one. Never drops a verdict.
export function supersede(file: AnswersFile, key: string): AnswersFile {
  if (file.itemsSha256 === key) return file;
  const hadAnswers = Object.keys(file.answers).length > 0;
  return {
    itemsSha256: key,
    answers: {},
    superseded: hadAnswers
      ? [...file.superseded, { itemsSha256: file.itemsSha256, answers: file.answers }]
      : file.superseded,
  };
}

export type SpotUiItem = {
  n: number;
  group: string;
  title: string;
  url: string | null;
  selector: string | null;
  test: string;
  recorded: string;
  // What the file already records for this item. The write guard used the checkbox as its only
  // proxy for "already answered", so it was blind to a verdict typed straight into the markdown --
  // and erased it while reporting success.
  answered: boolean;
  answerLine: string;
  // A held-out page: keep what was seen out of chat. SPOTCHECK.md holds those in its BAD groups;
  // the blind list is held-out throughout and says so only in its title, under a plain
  // "## Flags" -- matching the group alone marked none of its items.
  held: boolean;
};

// SPOTCHECK.md is generated by spotcheck.ts as a fixed five-line block per item (its renderer writes
// the number + checkbox + title, then open / test / recorded / agree lines).
export function parseSpotcheck(md: string): SpotUiItem[] {
  const items: SpotUiItem[] = [];
  let group = "";
  let listHeld = false;
  let cur: SpotUiItem | null = null;
  // Both start patterns end `(.*)$`, and in JS `.` does not match \r while `$` is not multiline, so
  // a CRLF worklist parsed to zero items and the UI reported "No items found".
  md = md.replace(/\r\n?/g, "\n");
  const push = (): void => {
    if (cur !== null) items.push(cur);
    cur = null;
  };
  for (const line of md.split("\n")) {
    const title = /^#\s+(.*)$/.exec(line);
    if (title) listHeld = /held.out/i.test(title[1]);
    const heading = /^##\s+(.*)$/.exec(line);
    if (heading) {
      push();
      group = heading[1].trim();
      continue;
    }
    const start = /^(\d+)\.\s+\[[ xX]\]\s+(.*)$/.exec(line);
    if (start) {
      push();
      cur = {
        n: Number(start[1]),
        group,
        title: start[2].trim(),
        url: null,
        selector: null,
        test: "",
        recorded: "",
        answered: /\[[xX]\]/.test(line),
        answerLine: "",
        held: listHeld || /BAD/i.test(group),
      };
      continue;
    }
    if (cur === null) continue;
    const open = /^\s+-\s+open\s+(.*)$/.exec(line);
    if (open) {
      cur.url = /<([^>]+)>/.exec(open[1])?.[1] ?? null;
      cur.selector = selectorFrom(/`([^`]+)`/.exec(open[1])?.[1] ?? null);
      continue;
    }
    const test = /^\s+-\s+test:\s*(.*)$/.exec(line);
    if (test) {
      cur.test = test[1].trim();
      continue;
    }
    const recorded = /^\s+-\s+recorded:\s*(.*)$/.exec(line);
    if (recorded) {
      cur.recorded = recorded[1].trim();
      continue;
    }
    const agree = /^\s+-\s+agree\?\s*\/\s*note:\s*(.*)$/.exec(line);
    if (agree) cur.answerLine = agree[1].trim();
  }
  push();
  return items;
}

// spotcheck.ts writes a BAD-element item as a url plus a CONSOLE EXPRESSION in backticks
// (`document.querySelectorAll("...").length`), not a bare selector. Handing that to querySelector
// throws, so the preview silently outlined nothing on those items. Pull the selector back out.
function selectorFrom(code: string | null): string | null {
  if (code === null) return null;
  const call = /querySelector(?:All)?\(\s*(["'])((?:\\.|(?!\1).)*)\1\s*\)/.exec(code);
  if (call) {
    try {
      return JSON.parse(`"${call[2].replace(/"/g, '\\"')}"`) as string;
    } catch {
      return call[2];
    }
  }
  // Anything still carrying JS syntax is not a selector; better no outline than a thrown one.
  return /[(){};]|=>/.test(code) ? null : code;
}

// Fills the "- agree? / note:" slot and ticks the box, leaving every other byte alone.
export function mergeIntoMd(
  md: string,
  answers: Record<string, { verdict: Verdict | null; note: string }>,
): string {
  let n: string | null = null;
  return md
    .split("\n")
    .map((line) => {
      // Any numbered line begins a new item, even one this writer does not recognise. Resetting
      // only on recognised ones meant the next "agree? / note:" after an odd checkbox was still
      // attributed to the PREVIOUS item -- a verdict written onto the wrong flag.
      const numbered = /^(\d+)\.\s/.test(line);
      const start = /^(\d+)\.\s+\[([ xX])\]\s+(.*)$/.exec(line);
      if (start) {
        n = start[1];
        return `${start[1]}. [${answers[n]?.verdict != null ? "x" : " "}] ${start[3]}`;
      }
      if (numbered) {
        n = null;
        return line;
      }
      if (n !== null && /^\s+-\s+agree\?\s*\/\s*note:/.test(line)) {
        const a = answers[n];
        const said = a?.verdict == null ? "" : ` ${a.verdict}`;
        // Collapse all whitespace: a note containing a newline would otherwise be written as extra
        // lines, and one shaped like "2. [x] **x**" would forge an item the reviewer never saw.
        const note = a?.note.trim()
          ? ` — ${a.note.trim().replace(/\s+/g, " ")}`
          : "";
        return `    - agree? / note:${said}${note}`;
      }
      return line;
    })
    .join("\n");
}

const sha256 = (s: string): string =>
  createHash("sha256").update(s).digest("hex");

// Identity of the drawn set: everything the generator chose, and nothing that a verdict, a parser
// improvement or the serving port can change.
//   - the url is reduced to its PATH: blind-labels.ts re-points local urls at whatever port the
//     reviewer runs on, and keying on the origin discarded the record when that port changed.
//   - the selector is excluded: it is parsed out of the open line, so improving the parser would
//     otherwise silently invalidate a completed record.
// An empty parse throws rather than keying as sha256(""), which every broken file shared -- so one
// broken worklist could be shown, and overwritten, with another's verdicts.
export function itemsKey(items: readonly SpotUiItem[]): string {
  if (items.length === 0)
    throw new Error("refusing to key an empty worklist: nothing was drawn");
  const pathOf = (url: string | null): string => {
    if (url === null) return "";
    const m = /^[a-z]+:\/\/[^/]+(\/.*)$/i.exec(url);
    return m === null ? url : m[1];
  };
  return sha256(
    items
      .map((i) => [i.n, i.title, pathOf(i.url), i.test, i.recorded].join("\u0000"))
      .join("\n"),
  );
}

function readAnswers(answersPath: string, spotSha: string): AnswersFile {
  const empty: AnswersFile = {
    itemsSha256: spotSha,
    answers: {},
    superseded: [],
  };
  if (!existsSync(answersPath)) return empty;
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(answersPath, "utf8"));
  } catch {
    // A truncated file is somebody's record, damaged. Refuse loudly rather than starting a clean
    // one over the top of it.
    throw new Error(
      `${answersPath} is not valid JSON. It holds the verdict record; move it aside deliberately rather than letting this overwrite it.`,
    );
  }
  const parsed = AnswersFileSchema.safeParse(raw);
  if (!parsed.success) throw new Error(`${answersPath} does not match the answers schema`);
  // A redraw remaps numbers to different items, so its answers must not be SHOWN -- but they are
  // still a human's work and are moved to `superseded` rather than dropped.
  return supersede(parsed.data, spotSha);
}

const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".gif": "image/gif",
  ".woff2": "font/woff2",
};

function staticFile(pathname: string): { body: Buffer; type: string } | null {
  const prefix = Object.keys(MOUNTS).find((p) => pathname.startsWith(p));
  if (prefix === undefined) return null;
  const root = resolve(MOUNTS[prefix as keyof typeof MOUNTS]);
  const file = resolve(join(root, pathname.slice(prefix.length)));
  // Refuse anything that escapes its mount.
  if (file !== root && !file.startsWith(root + sep)) return null;
  // realpath before the check: resolve()/join() are string operations and readFileSync follows
  // symlinks, so a link inside a mount would otherwise read straight through it.
  let real: string;
  try {
    real = realpathSync(file);
  } catch {
    return null;
  }
  if (real !== root && !real.startsWith(root + sep)) return null;
  // A directory (e.g. GET /corpus/, which resolves to the mount root) is not a file: readFileSync
  // would throw EISDIR out of the request handler and take the whole review server down mid-review.
  if (!statSync(real).isFile()) return null;
  return {
    body: readFileSync(real),
    type: MIME[extname(real).toLowerCase()] ?? "application/octet-stream",
  };
}

function main(argv: readonly string[]): void {
  const portFlag = argv.indexOf("--port");
  const port =
    portFlag === -1 ? DEFAULT_PORT : Number(argv[portFlag + 1] ?? DEFAULT_PORT);
  if (!Number.isInteger(port) || port <= 0) {
    console.error("--port must be a positive integer");
    process.exit(2);
  }
  // --file lets the same reviewer drive any spotcheck-shaped worklist (e.g. BLIND-LABELS.md);
  // each worklist keeps its verdicts in its own <name>-answers.json.
  const fileFlag = argv.indexOf("--file");
  const mdPath =
    fileFlag === -1 ? SPOTCHECK_MD : resolve(argv[fileFlag + 1] ?? SPOTCHECK_MD);
  const answersPath =
    fileFlag === -1
      ? ANSWERS_JSON
      : mdPath.replace(/\.md$/i, "") + "-answers.json";
  if (!existsSync(mdPath)) {
    console.error(
      `${mdPath} does not exist. Draw it first: npx tsx bench/spotcheck.ts`,
    );
    process.exit(2);
  }
  const origin = `http://127.0.0.1:${port}`;

  const server = createServer((req, res) => {
    const url = new URL(req.url ?? "/", origin);
    const send = (code: number, type: string, body: string | Buffer): void => {
      res.writeHead(code, {
        "content-type": type,
        "cache-control": "no-store",
      });
      res.end(body);
    };

    if (url.pathname === "/" || url.pathname === "/index.html")
      return send(200, "text/html; charset=utf-8", PAGE);

    if (url.pathname === "/api/items") {
      const md = readFileSync(mdPath, "utf8");
      const drawn = parseSpotcheck(md);
      // Key on the drawn items, BEFORE the preview url is rewritten below: the identity of an item
      // is what spotcheck.ts chose, not which port this process happens to serve it on.
      const key = itemsKey(drawn);
      const items = drawn.map((i) => ({
        ...i,
        // Point the preview at this server so it is same-origin and the target can be outlined.
        url: i.url === null ? null : i.url.replace(SERVE_ORIGIN, origin),
      }));
      return send(
        200,
        MIME[".json"],
        JSON.stringify({ items, ...readAnswers(answersPath, key) }),
      );
    }

    if (url.pathname === "/api/answer" && req.method === "POST") {
      let raw = "";
      req.on("data", (c) => (raw += c));
      req.on("end", () => {
        const parsed = z
          .object({
            n: z.number().int().positive(),
            verdict: VerdictSchema.nullable(),
            note: z.string(),
            // Which draw the reviewer was looking at when they judged.
            itemsSha256: z.string(),
          })
          .strict()
          .safeParse(JSON.parse(raw || "{}"));
        if (!parsed.success)
          return send(400, MIME[".json"], JSON.stringify({ ok: false }));
        const md = readFileSync(mdPath, "utf8");
        const spotSha = itemsKey(parseSpotcheck(md));
        // If the worklist was regenerated while this page was open, item 7 on screen is not item 7
        // on disk. Accepting the verdict would file a judgement against a flag nobody looked at.
        if (parsed.data.itemsSha256 !== spotSha)
          return send(
            409,
            MIME[".json"],
            JSON.stringify({
              ok: false,
              reason:
                "the worklist changed since this page was loaded; reload before judging further (nothing was saved, and no earlier verdict was lost)",
            }),
          );
        const file = readAnswers(answersPath, spotSha);
        // A worklist written before writtenToMd existed (both committed ones) left write-md no copy
        // to recognise, so the first changed answer locked it. A file that reads exactly what the
        // saved verdicts would write is that copy; one out of step may carry a hand edit, so is not.
        if (file.writtenToMd === undefined && mergeIntoMd(md, file.answers) === md)
          file.writtenToMd = { ...file.answers };
        file.answers[String(parsed.data.n)] = {
          verdict: parsed.data.verdict,
          note: parsed.data.note,
        };
        writeFileSync(answersPath, `${JSON.stringify(file, null, 2)}\n`);
        send(200, MIME[".json"], JSON.stringify({ ok: true }));
      });
      return;
    }

    if (url.pathname === "/api/write-md" && req.method === "POST") {
      const md = readFileSync(mdPath, "utf8");
      const file = readAnswers(answersPath, itemsKey(parseSpotcheck(md)));
      const done = Object.values(file.answers).filter(
        (a) => a.verdict !== null,
      ).length;
      // mergeIntoMd rewrites every checkbox and every answer line from the json, so anything the
      // file already records but the json does not would be erased. Refuse unless the json is a
      // superset of what is already written: saving must never subtract.
      // "Already recorded" means a ticked box OR text on the answer line -- these files are meant
      // to be fillable by hand (SPOTCHECK.md's own header describes a DevTools walk and never
      // mentions this tool), and judging only by the checkbox erased hand-written verdicts.
      const already = parseSpotcheck(md).filter(
        (i) => i.answered || i.answerLine !== "",
      );
      // Compare like with like: what each item would read after this write, and what it read after
      // this tool's last one. Checking only the first, through a hand-copied format that did not
      // match mergeIntoMd's, made the tool's own earlier copy look like a hand edit -- so changing a
      // verdict, or writing a note-only item, locked this button for good.
      const byN = (text: string): Map<number, SpotUiItem> =>
        new Map(parseSpotcheck(text).map((i) => [i.n, i]));
      const next = byN(mergeIntoMd(md, file.answers));
      const copied = byN(mergeIntoMd(md, file.writtenToMd ?? {}));
      // Nothing is lost if the other side shows it too: the tick, and any answer text.
      const keeps = (i: SpotUiItem, j: SpotUiItem | undefined): boolean =>
        j !== undefined &&
        (!i.answered || j.answered) &&
        (i.answerLine === "" || i.answerLine === j.answerLine);
      const wouldLose = already.filter(
        (i) => !keeps(i, next.get(i.n)) && !keeps(i, copied.get(i.n)),
      );
      if (done === 0 || wouldLose.length > 0)
        return send(
          200,
          MIME[".json"],
          JSON.stringify({
            ok: false,
            done,
            reason:
              done === 0
                ? "no verdicts to write"
                : `refusing: ${wouldLose.length} item(s) answered in the file differ from the saved verdicts (${wouldLose.map((i) => i.n).join(", ")})`,
          }),
        );
      writeFileSync(mdPath, mergeIntoMd(md, file.answers));
      writeFileSync(
        answersPath,
        `${JSON.stringify({ ...file, writtenToMd: file.answers }, null, 2)}\n`,
      );
      return send(200, MIME[".json"], JSON.stringify({ ok: true, done }));
    }

    const file = staticFile(url.pathname);
    if (file) return send(200, file.type, file.body);
    send(404, "text/plain; charset=utf-8", "not found");
  });

  server.on("error", (e: NodeJS.ErrnoException) => {
    console.error(
      e.code === "EADDRINUSE"
        ? `port ${port} is in use — this UI is probably already running at ${origin}. Open it, or pass --port <other>.`
        : e,
    );
    process.exitCode = 1;
  });
  server.listen(port, "127.0.0.1", () => {
    console.log(`spot-check UI  ${origin}`);
    console.log(`  items    ${mdPath}`);
    console.log(`  verdicts ${answersPath} (saved as you type)`);
    console.log("  Ctrl+C to stop");
  });
}

